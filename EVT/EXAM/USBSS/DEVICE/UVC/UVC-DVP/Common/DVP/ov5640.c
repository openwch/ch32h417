typedef struct
{
    uint16_t reg;
    uint8_t  val;
} ov5640_reg16_t;

/*******************************************************************************
 * @fn      ov5640_write_tbl16
 *
 * @brief   Write a 16-bit register table
 *
 * @return  0 - Success, 1 - Error
 */
static uint8_t ov5640_write_tbl16(const ov5640_reg16_t *tbl, uint16_t n)
{
    uint16_t i;

    for(i = 0; i < n; i++)
    {
        if(tbl[i].reg == 0x0000)
        {
            Delay_Ms(tbl[i].val);
            continue;
        }
        if(SCCB_WR_Reg16(tbl[i].reg, tbl[i].val))
        {
            return 1;
        }
    }
    return 0;
}

