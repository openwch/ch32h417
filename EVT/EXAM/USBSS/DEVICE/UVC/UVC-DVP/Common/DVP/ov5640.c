/* Frame order must match usb_desc.c. */
static const uint16_t ov5640_yuy2_res_HS[1][2] = {
    { 640,  480},
};
static const uint16_t ov5640_yuy2_res_SS[4][2] = {
    {1024,  768}, {1280,  720}, {1920, 1080}, {2592, 1944},
};

/*******************************************************************************
 * @fn      ov5640_set_framesize
 *
 * @brief   Apply the window table of a resolution
 *
 * @return  0 - Success, -1 - Error
 */
static int ov5640_set_framesize(uint16_t w, uint16_t h)
{
    uint16_t i;

    if(w == 640 && h == 480)
    {
        return 0;
    }

    for(i = 0; i < sizeof(s_ov5640_windows) / sizeof(s_ov5640_windows[0]); i++)
    {
        if(s_ov5640_windows[i].w == w && s_ov5640_windows[i].h == h)
        {
            return (int)ov5640_write_tbl16(s_ov5640_windows[i].tbl,
                                           s_ov5640_windows[i].n);
        }
    }
    return -1;
}

/*******************************************************************************
 * @fn      ov5640_set_vts
 *
 * @brief   Set the vertical total size
 *
 * @return  0 - Success, -1 - Error
 */
static int ov5640_set_vts(uint16_t w, uint16_t h, uint8_t is_hs)
{
    uint16_t i;

    for(i = 0; i < sizeof(s_ov5640_vts) / sizeof(s_ov5640_vts[0]); i++)
    {
        if(s_ov5640_vts[i].w == w && s_ov5640_vts[i].h == h)
        {
            uint16_t vts = is_hs ? s_ov5640_vts[i].hs_vts : s_ov5640_vts[i].ss_vts;
            if(SCCB_WR_Reg16(0x380E, (uint8_t)(vts >> 8))) return -1;
            if(SCCB_WR_Reg16(0x380F, (uint8_t)(vts & 0xFF))) return -1;
            return 0;
        }
    }
    return -1;
}

/*******************************************************************************
 * @fn      ov5640_set_pclk
 *
 * @brief   Set the PCLK divider
 *
 * @return  0 - Success, -1 - Error
 */
static int ov5640_set_pclk(uint8_t sysdiv_reg)
{
    if(SCCB_WR_Reg16(0x3036, 0x78)) return -1;
    if(SCCB_WR_Reg16(0x3035, sysdiv_reg)) return -1;
    if(SCCB_WR_Reg16(0x3034, 0x1A)) return -1;
    if(SCCB_WR_Reg16(0x3037, 0x13)) return -1;
    if(SCCB_WR_Reg16(0x3108, 0x01)) return -1;
    Delay_Ms(1);
    return 0;
}

/*******************************************************************************
 * @fn      ov5640_set_orient
 *
 * @brief   Apply the sensor orientation
 *
 * @return  0 - Success, -1 - Error
 */
static int ov5640_set_orient(void)
{
    uint8_t v;

    v = SCCB_RD_Reg16(0x3820);
    if(SCCB_WR_Reg16(0x3820, (uint8_t)((v & 0xF9u) | 0x06u))) return -1;  /* VFLIP = 1 */

    v = SCCB_RD_Reg16(0x3821);
    if(SCCB_WR_Reg16(0x3821, (uint8_t)(v & 0xF9u))) return -1;            /* HMIRROR = 0 */

    return 0;
}

/*******************************************************************************
 * @fn      OV5640_Detect
 *
 * @brief   Check the OV5640 product ID
 *
 * @return  1 - Present, 0 - Absent
 */
uint8_t OV5640_Detect(void)
{
    uint16_t pid;

    pid  = (uint16_t)SCCB_RD_Reg16(0x300A) << 8;
    pid |= SCCB_RD_Reg16(0x300B);

    return (uint8_t)(pid == OV5640_PID);
}

/*******************************************************************************
 * @fn      OV5640_Init
 *
 * @brief   Initialize the OV5640
 *
 * @return  0 - Success, 1 - Error
 */
uint8_t OV5640_Init(void)
{
    uint8_t reg;

    DVP_GPIO_Init();
    SCCB_Init();

    OV_PWDN_CLR;                        /* POWER ON */
    Delay_Ms(10);
    OV_RESET_CLR;
    Delay_Ms(10);
    OV_RESET_SET;
    Delay_Ms(10);

    /* Software reset: clear 0x3103 bit1, then 0x3008 = 0x82 */
    reg = SCCB_RD_Reg16(0x3103);
    if(SCCB_WR_Reg16(0x3103, (uint8_t)(reg & ~0x02u))) return 1;
    if(SCCB_WR_Reg16(0x3008, 0x82)) return 1;
    Delay_Ms(10);

    if(ov5640_write_tbl16(s_ov5640_evt_base,
                          sizeof(s_ov5640_evt_base) / sizeof(s_ov5640_evt_base[0]))) return 1;
    Delay_Ms(10);

    if(ov5640_write_tbl16(s_ov5640_mode_yuy2_640x480,
                          sizeof(s_ov5640_mode_yuy2_640x480) / sizeof(s_ov5640_mode_yuy2_640x480[0]))) return 1;
    Delay_Ms(50);

    ov5640_set_orient();

    printf("OV5640 init ok (YUY2)\r\n");
    return 0;
}

/*******************************************************************************
 * @fn      OV5640_Set_Pclk_Tier
 *
 * @brief   Select the PCLK tier
 *
 * @return  none
 */
void OV5640_Set_Pclk_Tier(uint8_t is_hs)
{
    ov5640_set_pclk(is_hs ? OV5640_PLL_MULT_HS : OV5640_PLL_MULT_SS);
}

/*******************************************************************************
 * @fn      OV5640_Format_Mode
 *
 * @brief   Select the output format
 *
 * @return  none
 */
void OV5640_Format_Mode(uint8_t choice)
{
    if(choice != FORMAT_YUV2)
    {
        printf("OV5640: only YUY2 is supported\r\n");
        return;
    }

    ov5640_write_tbl16(s_ov5640_mode_yuy2_640x480,
                       sizeof(s_ov5640_mode_yuy2_640x480) / sizeof(s_ov5640_mode_yuy2_640x480[0]));
    Delay_Ms(10);
    ov5640_set_orient();
}

/*******************************************************************************
 * @fn      OV5640_Change_Resolution
 *
 * @brief   Apply the negotiated frame
 *
 * @return  none
 */
void OV5640_Change_Resolution(uint8_t formatindex, uint8_t frameindex)
{
    uint8_t  is_hs;
    uint16_t w, h;

    if(formatindex != FORMAT_YUV2)
    {
        return;
    }

    is_hs = (uint8_t)((USB_Enum_Status == U2U3_SUCC) && USBHS_DevEnumStatus);

    if(frameindex < 1 || frameindex > (is_hs ? 1 : 4))
    {
        return;
    }

    if(is_hs)
    {
        w = ov5640_yuy2_res_HS[frameindex - 1][0];
        h = ov5640_yuy2_res_HS[frameindex - 1][1];
    }
    else
    {
        w = ov5640_yuy2_res_SS[frameindex - 1][0];
        h = ov5640_yuy2_res_SS[frameindex - 1][1];
    }

    Resolution_width  = w;
    Resolution_height = h;

    if(ov5640_set_framesize(w, h) != 0)
    {
        printf("OV5640: no window for %ux%u\r\n", w, h);
        return;
    }
    ov5640_set_vts(w, h, is_hs);
    ov5640_set_pclk(is_hs ? OV5640_PLL_MULT_HS : OV5640_PLL_MULT_SS);
    ov5640_set_orient();

    printf("OV5640: %ux%u %s\r\n", w, h, is_hs ? "HS" : "SS");
}
